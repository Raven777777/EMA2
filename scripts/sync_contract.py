#!/usr/bin/env python3
"""Generate extension/contract.js from contract/runtime.json.

The JSON file is the canonical source. The generated file is a classic
(no modules/imports) script that exposes the same structure on
globalThis.EMA2_CONTRACT.

Usage:
    python scripts/sync_contract.py
    python scripts/sync_contract.py --check
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PATH = ROOT / "contract" / "runtime.json"
TARGET_PATH = ROOT / "extension" / "contract.js"
SOURCE_LABEL = "contract/runtime.json"
TARGET_LABEL = "extension/contract.js"

VERSION_KEYS = (
    "productVersion",
    "guardVersion",
    "guardProtocolVersion",
    "helpersVersion",
)

TIMEOUT_KEYS = (
    "relayMarginSecs",
    "defaultSecs",
    "actSecs",
    "actExtensionGraceSecs",
    "actStepsSettleSecs",
    "jsDefaultSecs",
    "jsMaxSecs",
    "jsExtensionGraceSecs",
    "openDefaultSecs",
    "openExtensionGraceSecs",
    "waitDefaultSecs",
    "waitMaxSecs",
    "waitExtensionGraceSecs",
    "shotFilesSecs",
    "batchMaxSecs",
    "batchExtensionWatchdogMs",
    "toolWatchdogMs",
    "debuggerTaskTimeoutMs",
    "debuggerQueueTimeoutMs",
)

GENERATED_HEADER = (
    "// Generated by scripts/sync_contract.py from contract/runtime.json.\n"
    "// Do not edit this file manually; run `python scripts/sync_contract.py` to regenerate.\n"
    "// Classic script: installs a frozen globalThis.EMA2_CONTRACT.\n"
    "\n"
    "'use strict';\n"
    "\n"
)


def _is_positive_number(value: Any) -> bool:
    return (
        isinstance(value, (int, float))
        and not isinstance(value, bool)
        and math.isfinite(value)
        and value > 0
    )


def _format_number(value: float) -> str:
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return f"{value:g}"


def _reject_non_finite(value: str) -> None:
    raise ValueError(f"non-finite JSON number {value}")


def _reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate JSON key {key!r}")
        result[key] = value
    return result


def load_contract() -> dict[str, Any]:
    text = SOURCE_PATH.read_text(encoding="utf-8")
    data = json.loads(
        text,
        parse_constant=_reject_non_finite,
        object_pairs_hook=_reject_duplicate_keys,
    )
    if not isinstance(data, dict):
        raise ValueError("top-level value must be an object")
    return data


def validate(data: dict[str, Any]) -> list[tuple[str, str]]:
    errors: list[tuple[str, str]] = []

    for key in VERSION_KEYS:
        if key not in data:
            errors.append(("missing_key", f"{key} is required"))
            continue
        value = data[key]
        if key == "productVersion":
            if not isinstance(value, str) or not value.strip():
                errors.append(("invalid_version", "productVersion must be a non-empty string"))
        elif not _is_positive_number(value):
            errors.append(("invalid_version", f"{key} must be a positive number"))

    if "_comment" not in data and "notes" not in data:
        errors.append(("missing_key", "_comment or notes is required"))
    else:
        for key in ("_comment", "notes"):
            if key in data and (not isinstance(data[key], str) or not data[key].strip()):
                errors.append(("invalid_comment", f"{key} must be a non-empty string"))

    raw_timeouts = data.get("timeouts")
    if not isinstance(raw_timeouts, dict):
        errors.append(("invalid_timeouts", "timeouts must be an object"))
        return errors

    for key in TIMEOUT_KEYS:
        if key not in raw_timeouts:
            errors.append(("missing_timeout", f"timeouts.{key} is required"))
        elif not _is_positive_number(raw_timeouts[key]):
            errors.append(("invalid_timeout", f"timeouts.{key} must be a positive number"))

    def timeout(key: str) -> float | None:
        value = raw_timeouts.get(key)
        return value if _is_positive_number(value) else None

    relay_margin = timeout("relayMarginSecs")
    default_secs = timeout("defaultSecs")
    act_secs = timeout("actSecs")
    act_grace = timeout("actExtensionGraceSecs")
    js_default = timeout("jsDefaultSecs")
    js_grace = timeout("jsExtensionGraceSecs")
    open_default = timeout("openDefaultSecs")
    open_grace = timeout("openExtensionGraceSecs")
    wait_default = timeout("waitDefaultSecs")
    wait_grace = timeout("waitExtensionGraceSecs")
    shot_files = timeout("shotFilesSecs")
    batch_max = timeout("batchMaxSecs")
    batch_watchdog_ms = timeout("batchExtensionWatchdogMs")
    tool_watchdog_ms = timeout("toolWatchdogMs")

    if default_secs is not None and tool_watchdog_ms is not None:
        limit = tool_watchdog_ms / 1000
        if not default_secs > limit:
            errors.append(
                (
                    "default_gt_tool_watchdog",
                    f"defaultSecs={_format_number(default_secs)} must be > "
                    f"toolWatchdogMs/1000={_format_number(limit)}",
                )
            )

    if act_secs is not None and act_grace is not None and relay_margin is not None and tool_watchdog_ms is not None:
        total = act_secs + act_grace + relay_margin
        limit = tool_watchdog_ms / 1000
        if not total > limit:
            errors.append(
                (
                    "act_gt_tool_watchdog",
                    f"actSecs+actExtensionGraceSecs+relayMarginSecs="
                    f"{_format_number(total)} must be > "
                    f"toolWatchdogMs/1000={_format_number(limit)}",
                )
            )

    if js_default is not None and js_grace is not None and relay_margin is not None:
        left = js_default + relay_margin
        right = js_default + js_grace
        if not left > right:
            errors.append(
                (
                    "js_relay_margin_gt_grace",
                    f"jsDefaultSecs+relayMarginSecs={_format_number(left)} must be > "
                    f"jsDefaultSecs+jsExtensionGraceSecs={_format_number(right)}",
                )
            )

    if open_default is not None and open_grace is not None and relay_margin is not None:
        left = open_default + relay_margin
        right = open_default + open_grace
        if not left > right:
            errors.append(
                (
                    "open_relay_margin_gt_grace",
                    f"openDefaultSecs+relayMarginSecs={_format_number(left)} must be > "
                    f"openDefaultSecs+openExtensionGraceSecs={_format_number(right)}",
                )
            )

    if wait_default is not None and wait_grace is not None and relay_margin is not None:
        left = wait_default + relay_margin
        right = wait_default + wait_grace
        if not left > right:
            errors.append(
                (
                    "wait_relay_margin_gt_grace",
                    f"waitDefaultSecs+relayMarginSecs={_format_number(left)} must be > "
                    f"waitDefaultSecs+waitExtensionGraceSecs={_format_number(right)}",
                )
            )

    if shot_files is not None and tool_watchdog_ms is not None:
        if not shot_files * 1000 > tool_watchdog_ms:
            errors.append(
                (
                    "shot_files_gt_tool_watchdog",
                    f"shotFilesSecs*1000={_format_number(shot_files * 1000)} must be > "
                    f"toolWatchdogMs={_format_number(tool_watchdog_ms)}",
                )
            )

    if batch_max is not None and batch_watchdog_ms is not None:
        if not batch_max * 1000 > batch_watchdog_ms:
            errors.append(
                (
                    "batch_max_gt_extension_watchdog",
                    f"batchMaxSecs*1000={_format_number(batch_max * 1000)} must be > "
                    f"batchExtensionWatchdogMs={_format_number(batch_watchdog_ms)}",
                )
            )

    return errors


def _render_object(mapping: dict[str, Any], level: int) -> str:
    pad = "  " * level
    child_pad = "  " * (level + 1)
    lines = ["Object.freeze({"]
    items = list(mapping.items())
    for index, (key, value) in enumerate(items):
        comma = "," if index + 1 < len(items) else ""
        encoded_key = json.dumps(str(key), ensure_ascii=True)
        lines.append(f"{child_pad}{encoded_key}: {_render_value(value, level + 1)}{comma}")
    lines.append(f"{pad}}})")
    return "\n".join(lines)


def _render_value(value: Any, level: int) -> str:
    if isinstance(value, dict):
        return _render_object(value, level)
    if isinstance(value, list):
        if not value:
            return "[]"
        pad = "  " * level
        child_pad = "  " * (level + 1)
        lines = ["["]
        for index, item in enumerate(value):
            comma = "," if index + 1 < len(value) else ""
            lines.append(f"{child_pad}{_render_value(item, level + 1)}{comma}")
        lines.append(f"{pad}]")
        return "\n".join(lines)
    return json.dumps(value, ensure_ascii=True, allow_nan=False)


def generate(data: dict[str, Any]) -> str:
    return GENERATED_HEADER + "globalThis.EMA2_CONTRACT = " + _render_object(data, 0) + ";\n"


def _print_summary(data: dict[str, Any]) -> None:
    timeouts = data["timeouts"]
    print(f"contract source={SOURCE_LABEL}")
    print(
        f"product={data['productVersion']} "
        f"guard={_format_number(data['guardVersion'])} "
        f"guard_protocol={_format_number(data['guardProtocolVersion'])} "
        f"helpers={_format_number(data['helpersVersion'])}"
    )
    print(f"timeouts={len(timeouts)} validation=ok")


def _error(code: str, message: str, hint: str) -> None:
    print(f"error={code} msg={message} hint={hint}", file=sys.stderr)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate extension/contract.js from contract/runtime.json.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when extension/contract.js is missing or stale",
    )
    args = parser.parse_args(argv)

    try:
        data = load_contract()
    except FileNotFoundError:
        _error("contract_missing", f"{SOURCE_LABEL} not found", "create the canonical JSON file")
        return 1
    except (OSError, ValueError) as exc:
        _error("contract_invalid", str(exc).replace("\n", " "), f"fix {SOURCE_LABEL}")
        return 1

    errors = validate(data)
    if errors:
        for rule, message in errors:
            print(f"check=fail rule={rule} msg={message}", file=sys.stderr)
        print(
            f"error=contract_invalid errors={len(errors)} hint=fix {SOURCE_LABEL}",
            file=sys.stderr,
        )
        return 1

    payload = generate(data).encode("utf-8")

    if args.check:
        try:
            actual = TARGET_PATH.read_bytes()
        except FileNotFoundError:
            actual = None
        except OSError as exc:
            _error("contract_unreadable", str(exc).replace("\n", " "), f"check {TARGET_LABEL}")
            return 1

        if actual != payload:
            detail = "state=missing" if actual is None else f"actual_bytes={len(actual)}"
            _error(
                "contract_stale",
                f"target={TARGET_LABEL} expected_bytes={len(payload)} {detail}",
                "run python scripts/sync_contract.py",
            )
            return 1

        _print_summary(data)
        print(f"check=ok target={TARGET_LABEL} bytes={len(payload)}")
        return 0

    try:
        TARGET_PATH.parent.mkdir(parents=True, exist_ok=True)
        with open(TARGET_PATH, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(payload.decode("utf-8"))
    except OSError as exc:
        _error("contract_write_failed", str(exc).replace("\n", " "), f"write {TARGET_LABEL}")
        return 1

    _print_summary(data)
    print(f"wrote={TARGET_LABEL} bytes={len(payload)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
